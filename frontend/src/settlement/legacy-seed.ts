import type { LegacyResult } from './types'

/** 早年原始观测的机读结构；elev 为 null 表示该项缺失（缺高程） */
export type LegacyObs = {
  date: string
  /** merged 类型里上午=1、下午=2；single 默认为 1 */
  seq?: number
  elev: number | null
  operator?: string
  /** single=普通一条；merged=两次观测并记为一条；missing=缺高程/缺人员 */
  kind: 'single' | 'merged' | 'missing'
  note?: string
}

/** 给 LegacyResult 补上机读字段，文本字段照旧保留，便于追溯旧系统显示过什么 */
export type StructuredLegacyResult = LegacyResult & {
  首次观测日期: string
  首次高程m: number
  原始观测: LegacyObs[]
  重复提交?: { date: string; elev: number; operator: string; acceptedAt: string; duplicateAt: string }
}

